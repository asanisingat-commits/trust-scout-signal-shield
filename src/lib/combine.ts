const FAMILY_RE = /\b(accident|hospital|arrested|police station|lost my phone|new number|my phone (is )?broken|mum|mom|dad|son|daughter)\b|حادث|مستشفى|رقم جديد|ماما|بابا|أمي|أبي|ابنك|ابنتك/i;
const MONEY_LABELS = ["Payment request", "Untraceable payment method", "Urgency pressure", "Requests secret codes"];

export function analyzeCombined(input: CombinedInput, lang: Lang = "en"): Result {
  const T = L[lang];
  const signals: Signal[] = [];
  const text = input.text.trim();

  // 1. The message itself (existing tested rules).
  const msg = text ? analyzeMessage(text) : null;
  if (msg) signals.push(...msg.signals.map((s) => tr(s, lang)));
  if (text && FAMILY_RE.test(text)) signals.push({ label: T.familyLabel, detail: T.familyDetail, weight: 1.5 });

  // 2. Link, phone and bank details.
  // Skip if the message rules already scored this link (avoid counting it twice).
  const linkCounted = msg?.signals.some((s) => s.label === "Contains a suspicious link") ?? false;
  if (input.link.trim() && !linkCounted) {
    const u = analyzeUrl(input.link);
    if (u.score >= 4) signals.push({ label: T.linkLabel, detail: T.linkDetail(input.link.trim(), u.score), weight: Math.min(4, u.score / 2) });
  }
  if (input.phone.trim()) {
    for (const s of analyzePhone(input.phone).result.signals) { const x = tr(s, lang); signals.push({ ...x, label: T.phoneLabel(x.label) }); }
  }
  const iban = input.iban.trim() ? validateIban(input.iban) : null;
  if (iban) {
    if (iban.formatOk && !iban.checksumOk) signals.push({ label: T.ibanBadLabel, detail: T.ibanBadDetail, weight: 2 });
    signals.push({ label: T.ibanLabel, detail: T.ibanDetail, weight: 1 });
  }

  // 3. The media (voice note / image / video).
  const hasMedia = input.mediaKind !== "none";
  if (hasMedia) {
    signals.push({ label: T.mediaLabel[input.mediaKind as Exclude<MediaKind, "none">], detail: T.mediaDetail, weight: 0.5 });
    if (input.media?.status === "likely_fake") signals.push({ label: T.fakeLabel, detail: T.fakeDetail(input.media.source), weight: 3.5 });
    if (input.media?.metadataAi) signals.push({ label: T.metaLabel, detail: T.metaDetail(input.media.metadataAi), weight: 3 });
  }

  // 4. The combination: media + money is where people actually lose money.
  const moneyAsked = !!iban || (msg?.signals.some((s) => MONEY_LABELS.includes(s.label)) ?? false);
  if (hasMedia && moneyAsked) signals.push({ label: T.comboLabel, detail: T.comboDetail, weight: 2.5 });

  const notes = [T.notes.base];
  if (hasMedia && (!input.media || input.media.status === "not_checked")) notes.push(T.notes.notChecked);
  if (hasMedia) notes.push(T.notes.detection);
  return finalize(signals, T.recs, notes);
}

/** Map a Hugging Face classification output to our three honest labels. */
export function interpretDetection(preds: { label: string; score: number }[]): MediaFinding["status"] {
  if (!Array.isArray(preds) || preds.length === 0) return "inconclusive";
  const FAKE = /fake|spoof|deepfake|synthetic|generated|artificial|\bai\b|manipulated/i;
  const REAL = /real|bona ?fide|human|genuine|authentic|natural/i;
  const fake = preds.find((p) => FAKE.test(p.label) && !/not/i.test(p.label));
  const real = preds.find((p) => REAL.test(p.label) && !FAKE.test(p.label));
  const fakeScore = fake ? fake.score : real ? 1 - real.score : null;
  if (fakeScore === null) return "inconclusive";
  if (fakeScore >= 0.7) return "likely_fake";
  if (fakeScore <= 0.3) return "no_signs";
  return "inconclusive";
}

