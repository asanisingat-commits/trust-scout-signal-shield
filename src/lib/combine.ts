// (a voice note / image / video + the message + a link, phone number or IBAN).
// Pure and tested (combine.test.ts). Every point still comes from a named rule.
import { analyzeMessage, analyzePhone, analyzeUrl, finalize, validateIban, type Result, type Signal } from "./detect";

export type MediaKind = "none" | "voice" | "image" | "video";

export type MediaFinding = {
  /** Result of the AI detection model, when one is connected. */
  status: "likely_fake" | "inconclusive" | "no_signs" | "not_checked";
  /** Which model or method produced the finding, shown for transparency. */
  source: string;
  /** Generator name found in the image's own metadata (e.g. "Midjourney"), if any. */
  metadataAi?: string | null;
};

export type CombinedInput = {
  text: string;
  link: string;
  phone: string;
  iban: string;
  mediaKind: MediaKind;
  media?: MediaFinding | undefined;
};

